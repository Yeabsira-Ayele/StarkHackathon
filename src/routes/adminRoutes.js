router.put('/admin/campaigns/:id', requireAuth, requireAdmin, adminController.reviewCampaign);
router.get('/admin/donations', requireAuth, requireAdmin, adminController.getAdminDonations);
router.get('/admin/users', requireAuth, requireAdmin, adminController.getAdminUsers);
router.get('/admin/users/:id', requireAuth, requireAdmin, adminController.getAdminUserById);
router.patch('/admin/users/:id/status', requireAuth, requireAdmin, adminController.updateUserStatus);
router.get('/admin/admins', requireAuth, requireSuperAdmin, adminController.getAdmins);
router.get('/admin/admin-candidates', requireAuth, requireSuperAdmin, adminController.getAdminCandidates);
router.post('/admin/admins', requireAuth, requireSuperAdmin, adminController.addAdmin);
router.delete('/admin/admins/:id', requireAuth, requireSuperAdmin, adminController.removeAdmin);

module.exports = router;
