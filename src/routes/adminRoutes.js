const express = require('express');
const router = express.Router();
const adminController = require('../controllers/adminController');
const { requireAuth } = require('../middleware/authMiddleware');
const { requireAdmin, requireSuperAdmin } = require('../middleware/roleMiddleware');

router.get('/admin/dashboard', requireAuth, requireAdmin, adminController.getDashboard);
router.get('/admin/activity', requireAuth, requireAdmin, adminController.getAdminActivity);
router.get('/admin/campaigns', requireAuth, requireAdmin, adminController.getPendingCampaigns);
router.get('/admin/fundraisers/pending', requireAuth, requireAdmin, adminController.getPendingCampaigns);
router.get('/admin/fundraisers/:id', requireAuth, requireAdmin, adminController.getCampaignReview);
router.get('/admin/fundraisers/:id/review', requireAuth, requireAdmin, adminController.getCampaignReview);
router.patch('/admin/fundraisers/:id', requireAuth, requireAdmin, adminController.reviewCampaign);
router.put('/admin/fundraisers/:id', requireAuth, requireAdmin, adminController.reviewCampaign);
router.patch('/admin/fundraisers/:id/approve', requireAuth, requireAdmin, adminController.approveCampaign);
router.put('/admin/fundraisers/:id/approve', requireAuth, requireAdmin, adminController.approveCampaign);
